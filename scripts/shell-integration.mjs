import { mkdir, readFile, writeFile, rename, copyFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { homedir } from 'node:os'

export const shellQuote = value => "'" + value.replaceAll("'", "'\\''") + "'"
const read = file => readFile(file, 'utf8').catch(error => { if (error.code === 'ENOENT') return ''; throw error })
async function save(file, text, mode = 0o600) {
  await mkdir(dirname(file), { recursive: true })
  const temporary = `${file}.${process.pid}.tmp`
  await writeFile(temporary, text, { mode }); await rename(temporary, file)
}

/** Bind interactive Codex only inside registered workspaces. No history is
 * copied and explicit CODEX_HOME / other directories keep their own library. */
export async function installShellIntegration({ root, codexHome, home = homedir() }) {
  const directory = resolve(home, '.config/cweb'), registry = resolve(directory, 'workspaces.json')
  await mkdir(directory, { recursive: true, mode: 0o700 })
  const entries = JSON.parse(await read(registry) || '[]').filter(entry => entry.root !== root)
  entries.push({ root, codexHome }); entries.sort((a, b) => b.root.length - a.root.length)
  const routes = entries.map(entry => `    ${shellQuote(entry.root)}|${shellQuote(entry.root)}/*) CODEX_HOME=${shellQuote(entry.codexHome)} command codex "$@"; return $? ;;`).join('\n')
  const script = `# Generated by cweb; workspace routing shares the live native library.
_cweb_workspace_codex() {
  if [[ -n "\${CODEX_HOME:-}" ]]; then command codex "$@"; return $?; fi
  local cweb_directory="$(pwd -P)" cweb_argument cweb_cd_next=false
  for cweb_argument in "$@"; do
    if $cweb_cd_next; then cweb_directory="$(cd -- "$cweb_argument" 2>/dev/null && pwd -P)" || { command codex "$@"; return $?; }; break; fi
    case "$cweb_argument" in
      --) break ;;
      -C|--cd) cweb_cd_next=true ;;
      -C?*) cweb_directory="$(cd -- "\${cweb_argument#-C}" 2>/dev/null && pwd -P)" || { command codex "$@"; return $?; }; break ;;
      --cd=*) cweb_directory="$(cd -- "\${cweb_argument#--cd=}" 2>/dev/null && pwd -P)" || { command codex "$@"; return $?; }; break ;;
    esac
  done
  case "$cweb_directory" in
${routes}
  esac
  command codex "$@"
}
if ! alias codex &>/dev/null && { ! declare -F codex &>/dev/null || [[ "$(declare -f codex)" == *'_cweb_workspace_codex'* ]]; }; then
  codex() { _cweb_workspace_codex "$@"; }
fi
`
  await save(registry, JSON.stringify(entries, null, 2) + '\n')
  await save(resolve(directory, 'shell.bash'), script)
  const block = `# >>> cweb shell integration >>>
case ":$PATH:" in *":$HOME/.local/bin:"*) ;; *) export PATH="$HOME/.local/bin:$PATH" ;; esac
if [ -n "\${BASH_VERSION:-}" ] && [ -r "$HOME/.config/cweb/shell.bash" ]; then
  . "$HOME/.config/cweb/shell.bash"
fi
# <<< cweb shell integration <<<`
  for (const name of ['.bashrc', '.profile']) {
    const file = resolve(home, name), before = await read(file)
    const without = before.replace(/# >>> cweb shell integration >>>[\s\S]*?# <<< cweb shell integration <<</g, '').trimEnd()
    const after = without + '\n\n' + block + '\n'
    if (after === before) continue
    if (before) { const backup = resolve(directory, 'backups', `${Date.now()}-${name}`); await mkdir(dirname(backup), { recursive: true, mode: 0o700 }); await copyFile(file, backup) }
    await save(file, after)
  }
  return { registry, shell: resolve(directory, 'shell.bash') }
}
