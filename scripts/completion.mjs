import { lstat, mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises'
import { homedir } from 'node:os'
import { dirname, isAbsolute, resolve } from 'node:path'
import { randomUUID } from 'node:crypto'
import { cliCommands, completionActions } from './cli-commands.mjs'

const marker = '# cweb Bash completion; generated by cweb completion install\n'
export function bashCompletion() {
  const cases = Object.entries(cliCommands).map(([name, options]) => `        ${name}) candidates='${options.join(' ')}' ;;`).join('\n')
  return `${marker}# No default/command/file fallback. Tab never starts a service or invokes Node.
_cweb_complete() {
    local cur="\${COMP_WORDS[COMP_CWORD]-}" word action='' extra='' candidates='' candidate
    local i expect_port=0 end_options=0
    COMPREPLY=()
    for ((i=1; i<COMP_CWORD; i++)); do
        word="\${COMP_WORDS[i]}"
        if ((expect_port)); then
            [[ $word == = ]] || expect_port=0
            continue
        fi
        if ((!end_options)); then
            case "$word" in
                --port) expect_port=1; continue ;;
                --port=*) continue ;;
                --help|-h) return 0 ;;
                --) end_options=1; continue ;;
                -*) continue ;;
            esac
        fi
        if [[ -z $action ]]; then action=$word; else extra=$word; fi
    done
    ((expect_port)) && return 0
    [[ $cur == --port=* ]] && return 0
    if [[ -z $action ]]; then
        if [[ $cur == -* && $end_options == 0 ]]; then candidates='${[...new Set(Object.values(cliCommands).flat())].join(' ')}'
        else candidates='${Object.keys(cliCommands).join(' ')}'; fi
    elif [[ -n $extra ]]; then
        [[ $action == completion && $cur == -* && $end_options == 0 ]] && candidates='--help'
    elif [[ $action == completion && $cur != -* ]]; then
        candidates='${completionActions.join(' ')}'
    elif ((!end_options)); then
        case "$action" in
${cases}
        esac
    fi
    for candidate in $candidates; do
        [[ $candidate == "$cur"* ]] || continue
        if [[ $candidate == --* ]]; then
            for ((i=1; i<COMP_CWORD; i++)); do
                [[ \${COMP_WORDS[i]} == "$candidate" || \${COMP_WORDS[i]} == "$candidate="* ]] && break
            done
            ((i<COMP_CWORD)) && continue
        fi
        COMPREPLY+=("$candidate")
    done
    return 0
}
complete -F _cweb_complete cweb ./cweb
`
}

export function completionPath() {
  const userDirectory = process.env.BASH_COMPLETION_USER_DIR
  const dataDirectory = process.env.XDG_DATA_HOME
  for (const value of [userDirectory, dataDirectory]) if (value && !isAbsolute(value)) throw new Error('Bash 补全目录必须使用绝对路径。')
  return resolve(userDirectory || resolve(dataDirectory || resolve(homedir(), '.local/share'), 'bash-completion'), 'completions/cweb')
}

export async function installBashCompletion() {
  const target = completionPath(), script = bashCompletion()
  const existing = await lstat(target).catch(error => { if (error.code === 'ENOENT') return null; throw error })
  if (existing) {
    if (!existing.isFile() || !(await readFile(target, 'utf8')).startsWith(marker)) throw new Error(`已有自定义补全，未覆盖：${target}。可运行 source <(cweb completion bash) 在当前 Bash 启用。`)
    if (await readFile(target, 'utf8') === script) return target
  }
  await mkdir(dirname(target), { recursive: true })
  const temporary = `${target}.${randomUUID()}.tmp`
  try {
    await writeFile(temporary, script, { mode: 0o600, flag: 'wx' })
    // A first install must never replace a file created by another installer.
    if (!existing) await writeFile(target, script, { mode: 0o600, flag: 'wx' })
    else await rename(temporary, target)
  } finally { await rm(temporary, { force: true }) }
  return target
}
